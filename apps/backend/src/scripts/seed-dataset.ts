export interface SeedProductVariant {
  sku: string;
  size?: string;
  color?: string;
  colorHex?: string;
  price: number;
  mrp: number;
  stock: number;
  images: string[];
  isActive: boolean;
}

export interface SeedProduct {
  name: string;
  slug: string;
  description: string;
  category: ProductCategory | string;
  subCategory: string;
  subType: ProductSubType | string;
  brand: string;
  tags: string[];
  attributes?: Array<{ key: string; value: string }>;
  isFeatured: boolean;
  variants: SeedProductVariant[];
}

export interface MerchantSeedDefinition {
  user: {
    fullName: string;
    email: string;
    phone: string;
    password: string;
    role: UserRole;
    isVerified: boolean;
    isActive: boolean;
  };
  store: {
    name: string;
    slug: string;
    description: string;
    category: StoreCategory;
    logoUrl: string;
    bannerUrl: string;
    location: {
      type: 'Point';
      coordinates: [number, number]; // [lng, lat]
    };
    address: {
      street: string;
      landmark: string;
      city: string;
      state: string;
      pincode: string;
    };
    operatingHours: any;
    deliveryRadiusKm: number;
    approvalStatus: StoreApprovalStatus;
    isActive: boolean;
    rating: number;
    reviewCount: number;
    legalDetails: {
      gstin: string;
      pan: string;
      legalBusinessName: string;
      isGstVerified: boolean;
    };
    bankDetails: {
      accountNumber: string;
      ifscCode: string;
      accountHolderName: string;
      bankName: string;
      isVerified: boolean;
    };
  };
  products?: SeedProduct[];
}

